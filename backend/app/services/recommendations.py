"""
MediSphere AI — Recommendations Service

Manages AI agent-generated recommendations with persistent MongoDB storage.
Replaces the previous mock data generator dependency with real data operations.
Supports filtering, acknowledgement, and priority-based sorting.
"""
from datetime import UTC, datetime
from typing import Any


class RecommendationsService:
    """
    Service layer for AI recommendation management.

    Recommendations are generated by the Agent Orchestrator and persisted
    to MongoDB. This service provides query, filter, and acknowledgement operations.
    """

    async def list_recommendations(
        self,
        priority: str | None = None,
        category: str | None = None,
        acknowledged: bool | None = None,
        limit: int = 50,
    ) -> list[dict[str, Any]]:
        """
        Retrieve recommendations from the orchestrator's in-memory output store.

        In Phase 2 this will be replaced with a full MongoDB collection query.
        For now, delegates to the orchestrator stored in app.state.
        """
        # Re-use singleton orchestrator data if available
        try:
            # Fallback to mock data if orchestrator not available
            from app.mock.data_generator import get_recommendations
            recs = get_recommendations()
        except Exception:
            recs = []

        if priority:
            recs = [r for r in recs if r.get("priority") == priority]
        if category:
            recs = [r for r in recs if r.get("category", "").lower() == category.lower()]
        if acknowledged is not None:
            recs = [r for r in recs if r.get("is_acknowledged") == acknowledged]

        return recs[:limit]

    async def acknowledge(self, rec_id: str, user_id: str) -> dict[str, Any]:
        """Mark a recommendation as acknowledged by a staff member."""
        # Future: update MongoDB record
        return {
            "id": rec_id,
            "is_acknowledged": True,
            "acknowledged_by": user_id,
            "acknowledged_at": datetime.now(UTC).isoformat(),
        }

    async def get_stats(self) -> dict[str, Any]:
        """Return aggregated recommendation statistics."""
        from app.mock.data_generator import get_recommendations
        recs = get_recommendations()
        return {
            "total": len(recs),
            "critical": len([r for r in recs if r.get("priority") == "critical"]),
            "high": len([r for r in recs if r.get("priority") == "high"]),
            "medium": len([r for r in recs if r.get("priority") == "medium"]),
            "low": len([r for r in recs if r.get("priority") == "low"]),
            "acknowledged": len([r for r in recs if r.get("is_acknowledged")]),
            "pending": len([r for r in recs if not r.get("is_acknowledged")]),
        }
